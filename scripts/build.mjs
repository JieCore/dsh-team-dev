/**
 * Bundle the master sources into lib/: the team-dev composition
 * (src/guard.ts + src/provider.js + src/index.js) and the separate
 * session-changes plugin (src/session-changes/index.js), then run the smoke
 * check. The lib/ directory is build output only — edit src/, never lib/.
 */
import { execFileSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import { join } from 'node:path'

const root = fileURLToPath(new URL('..', import.meta.url))
const repo = join(root, '..', 'deepseek-harness')
const esbuild = join(repo, 'node_modules/.pnpm/esbuild@0.25.12/node_modules/esbuild/bin/esbuild')
const builds = [
  ['src/index.js', 'lib/index.js'],
  ['src/session-changes/index.js', 'lib/session-changes.js'],
]
const mainBanner = '// GENERATED by scripts/build.mjs from src/ — do not edit.\n'
  + '// Behavioral parity pinned by packages/guard/step-budget/tests/artifact-parity.spec.ts.'
for (const [entry, outfile] of builds) {
  const banner = entry === 'src/index.js'
    ? mainBanner
    : `// GENERATED by scripts/build.mjs from ${entry} — do not edit.`
  execFileSync(esbuild, [entry, '--bundle', '--format=esm', '--platform=node', `--outfile=${outfile}`, '--log-level=warning',
    `--banner:js=${banner}`],
    { cwd: root, stdio: 'inherit' })
}
execFileSync(process.execPath, ['scripts/verify.mjs'], { cwd: root, stdio: 'inherit' })
console.log('build: lib/index.js + lib/session-changes.js regenerated')
