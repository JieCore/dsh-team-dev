/**
 * Bundle the master source (src/guard.ts + src/provider.js + src/index.js)
 * into lib/index.js and run the smoke check. The lib/ directory is build
 * output only — edit src/, never lib/.
 */
import { execFileSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import { join } from 'node:path'

const root = fileURLToPath(new URL('..', import.meta.url))
const repo = join(root, '..', 'deepseek-harness')
const esbuild = join(repo, 'node_modules/.pnpm/esbuild@0.25.12/node_modules/esbuild/bin/esbuild')
execFileSync(esbuild, ['src/index.js', '--bundle', '--format=esm', '--platform=node', '--outfile=lib/index.js', '--log-level=warning',
  `--banner:js=// GENERATED by scripts/build.mjs from src/ — do not edit.\n// Behavioral parity pinned by packages/guard/step-budget/tests/artifact-parity.spec.ts.`],
  { cwd: root, stdio: 'inherit' })
execFileSync(process.execPath, ['scripts/verify.mjs'], { cwd: root, stdio: 'inherit' })
console.log('build: lib/index.js regenerated')
