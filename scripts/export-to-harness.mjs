/**
 * Reverse export: generate the harness-side test facade
 * (deepseek-harness/packages/guard/step-budget/src/index.ts) from THIS
 * project's master source, adding the schemastery Config schema, identity
 * rows, and real imports the repository package needs for its gates.
 * The repository package owns tests/CI only; the source lives here.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join, resolve } from 'node:path'

const root = fileURLToPath(new URL('..', import.meta.url))
const repoArg = process.argv.indexOf('--repo')
const repo = repoArg !== -1 ? resolve(process.argv[repoArg + 1]) : join(root, '..', 'deepseek-harness')

let t = readFileSync(join(root, 'src/guard.ts'), 'utf8')
// 去掉主源头注
t = t.replace(/^\/\/ Hand-written master source[^\n]*\n/, '')

// 主源 → 仓库壳的手术（build.mjs 的逆操作）
t = t.replace("import { createUserMessage } from './provider.js'\n", '')
t = t.replaceAll("plugin: 'dsh-team-dev'", "plugin: 'step-budget-guard'")
t = t.replace('export function guardApply(ctx, config = {}): void {', 'export function apply(ctx: Context, config: Config): void {')
t = t.replaceAll('config.softThreshold ?? 20', 'config.softThreshold as number')
t = t.replaceAll('config.hardThreshold ?? 25', 'config.hardThreshold as number')
t = t.replaceAll("(config.allow ?? ['write', 'edit', 'team_task_update', 'send_message'])", '(config.allow as string[])')
t = t.replaceAll('(config.include ?? [])', '(config.include as string[])')
t = t.replaceAll('(config.exclude ?? [])', '(config.exclude as string[])')
t = t.replace('if (!(config.onlyTeamMembers ?? true)) return true', 'if (!config.onlyTeamMembers) return true')
t = t.replaceAll('dsh-team-dev:', 'step-budget-guard:')
t = t.replaceAll("console.error('[dsh-team-dev:guard] per-agent observer installed')", "console.error('[step-budget-guard] per-agent observer installed')")

const facade = `// GENERATED by dsh-team-dev/scripts/export-to-harness.mjs — the hand-written
// source lives at dsh-team-dev/src/guard.ts; edit it there and re-run the
// exporter. This file exists so the repository package can type-check, cover,
// and upstream the guard while the product project owns the source.

import type { Context } from '@deepseek-ai/cordis'
import z from '@deepseek-ai/schemastery'
import type { Agent, PreStepDecision } from '@deepseek-ai/dsh-agent'
import { createUserMessage } from '@deepseek-ai/dsh-llm'
import type { MessageSource } from '@deepseek-ai/dsh-llm'
import type { UserMessage } from '@deepseek-ai/dsh-session'
import type { PostToolDecision, PreToolDecision, ToolExecution } from '@deepseek-ai/dsh-tools'

export const name = 'step-budget-guard'
export const inject = ['agents']

export interface Config {
  softThreshold?: number
  hardThreshold?: number
  allow?: string[]
  include?: string[]
  exclude?: string[]
  onlyTeamMembers?: boolean
}

export const Config: z<Config> = z.object({
  softThreshold: z.number().default(20),
  hardThreshold: z.number().default(25),
  allow: z.array(z.string()).default(['write', 'edit', 'team_task_update', 'send_message']),
  include: z.array(z.string()).default([]),
  exclude: z.array(z.string()).default([]),
  onlyTeamMembers: z.boolean().default(true),
})

${t}`
writeFileSync(join(repo, 'packages/guard/step-budget/src/index.ts'), facade)
console.log(`export: wrote ${join(repo, 'packages/guard/step-budget/src/index.ts')}`)
